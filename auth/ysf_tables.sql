-- Visitor accounts for 袁淑芳, kept in the shared ChainFuel database.
-- The ysf_ prefix is the whole set to move when this project gets its own database.

CREATE TABLE IF NOT EXISTS ysf_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  name text NOT NULL DEFAULT '',
  password_hash text NOT NULL,
  country text NOT NULL DEFAULT '',
  occupation text NOT NULL DEFAULT '',
  interests text NOT NULL DEFAULT '',
  found_via text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ysf_users_email_uniq UNIQUE (email)
);

ALTER TABLE ysf_users ADD COLUMN IF NOT EXISTS country text NOT NULL DEFAULT '';
ALTER TABLE ysf_users ADD COLUMN IF NOT EXISTS occupation text NOT NULL DEFAULT '';
ALTER TABLE ysf_users ADD COLUMN IF NOT EXISTS interests text NOT NULL DEFAULT '';
ALTER TABLE ysf_users ADD COLUMN IF NOT EXISTS found_via text NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS ysf_contributions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES ysf_users (id) ON DELETE CASCADE,
  kind text NOT NULL,
  title text NOT NULL,
  body text NOT NULL,
  source text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ysf_contributions_kind_chk CHECK (kind IN ('formula', 'clue'))
);

CREATE INDEX IF NOT EXISTS ysf_contributions_user_id_idx ON ysf_contributions (user_id, id);

CREATE TABLE IF NOT EXISTS ysf_chats (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES ysf_users (id),
  role text NOT NULL,
  content text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ysf_chats_role_chk CHECK (role IN ('user', 'assistant'))
);

CREATE INDEX IF NOT EXISTS ysf_chats_user_id_idx ON ysf_chats (user_id, id);

CREATE TABLE IF NOT EXISTS ysf_sessions (
  token text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES ysf_users (id),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
