-- Visitor accounts for 袁淑芳, kept in the shared ChainFuel database.
-- The ysf_ prefix is the whole set to move when this project gets its own database.

CREATE TABLE IF NOT EXISTS ysf_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  name text NOT NULL DEFAULT '',
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ysf_users_email_uniq UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS ysf_sessions (
  token text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES ysf_users (id),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
